// اختبار شامل للواجهة في الوضع التجريبي باستخدام Playwright
// التشغيل: npm run build && npx vite preview --port 4173 &  ثم  node scripts/e2e.cjs
const { chromium } = require('playwright')
const path = require('path')
const fs = require('fs')

const BASE = process.env.BASE_URL || 'http://localhost:4173/'
const OUT = process.env.SHOTS_DIR || path.join(__dirname, '..', 'test-results')
fs.mkdirSync(OUT, { recursive: true })

let step = 0
const log = (m) => console.log(`✔ ${++step}. ${m}`)
const assert = (cond, msg) => {
  if (!cond) throw new Error(`ASSERTION FAILED: ${msg}`)
}

async function main() {
  const browser = await chromium.launch()
  const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, locale: 'ar' })
  const page = await ctx.newPage()
  const errors = []
  page.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
  page.on('pageerror', (e) => errors.push(`PAGEERROR ${e.message}`))
  const shot = (name) => page.screenshot({ path: path.join(OUT, `${name}.png`), fullPage: false })

  const login = async (label) => {
    await page.waitForSelector('button[type="submit"]:has-text("دخول")')
    await page.click(`button:has-text("${label}")`)
    await page.waitForSelector('aside nav')
  }
  const logout = async () => {
    await page.click('header button[aria-haspopup="menu"]')
    await page.click('[role="menuitem"]:has-text("تسجيل الخروج")')
    await page.click('[role="dialog"] button:has-text("خروج")')
    await page.waitForSelector('button[type="submit"]:has-text("دخول")')
  }
  const toastText = () => page.locator('[aria-live="polite"]').innerText()
  const cell = (r, c) => page.locator(`input[data-r="${r}"][data-c="${c}"]`)

  await page.goto(BASE)
  await page.evaluate(() => localStorage.clear())
  await page.goto(BASE)
  await shot('01-login')
  log('login page renders')

  // ===== التدريسي: إدخال الدرجات =====
  await login('تدريسي')
  await page.waitForSelector('text=موادي الدراسية')
  await shot('02-teacher-dashboard')
  log('teacher dashboard')

  await page.click('a:has-text("التشريح الشعاعي للرأس والأطراف العليا")')
  await page.waitForSelector('table.grade-grid')
  await cell(0, 0).click()
  await page.keyboard.type('20')
  await page.keyboard.press('ArrowLeft')
  await page.keyboard.type('12')
  await page.keyboard.press('ArrowLeft')
  await page.keyboard.type('20')
  await page.keyboard.press('ArrowLeft')
  await page.keyboard.type('30')
  await page.keyboard.press('Enter')
  const row0 = page.locator('table.grade-grid tbody tr').nth(0)
  assert((await row0.innerText()).includes('82'), 'row 0 total should be 82')
  assert((await row0.innerText()).includes('جيد جداً'), 'row 0 grade label')
  assert(await cell(1, 3).evaluate((el) => el === document.activeElement), 'Enter moves down in the same column')
  log('keyboard entry + automatic total (20+12+20+30 = 82, جيد جداً)')

  // لصق كتلة من Excel
  await cell(1, 0).focus()
  await page.evaluate(() => {
    const el = document.activeElement
    const dt = new DataTransfer()
    dt.setData('text/plain', '18\t12\t20\t30\r\n10\t5\t10\t20\r\n15\tغ\t\t\r\n')
    el.dispatchEvent(new ClipboardEvent('paste', { clipboardData: dt, bubbles: true, cancelable: true }))
  })
  const rows = page.locator('table.grade-grid tbody tr')
  assert((await rows.nth(1).innerText()).includes('80'), 'pasted row 1 total = 80')
  assert((await rows.nth(2).innerText()).includes('45'), 'pasted row 2 total = 45')
  assert((await rows.nth(2).innerText()).includes('ضعيف'), 'row 2 fails (ضعيف)')
  assert((await rows.nth(3).locator('select').inputValue()) === 'absent', 'غ in paste sets absent')
  log('multi-cell paste from Excel (incl. «غ» → غائب)')

  // قيمة تتجاوز الحد
  await cell(4, 0).click()
  await page.keyboard.type('30')
  await page.keyboard.press('Enter')
  assert((await rows.nth(4).locator('td.cell-error').count()) === 1, 'over-max value is flagged')
  await page.waitForSelector('[data-save-state="invalid"]')
  await cell(4, 0).click()
  await page.keyboard.type('25')
  await page.keyboard.press('Enter')
  log('over-max value highlighted and blocks saving until fixed')

  await page.waitForSelector('[data-save-state="saved"]', { timeout: 8000 })
  await shot('03-grade-entry')
  await page.reload()
  await page.waitForSelector('table.grade-grid')
  assert((await cell(0, 0).inputValue()) === '20', 'grade persisted after reload')
  assert((await rows.nth(1).innerText()).includes('80'), 'pasted grades persisted')
  log('autosave persisted grades across reload')

  // الإرسال للجنة
  await page.click('button:has-text("إرسال إلى اللجنة")')
  await page.waitForSelector('[role="dialog"]:has-text("درجات ناقصة")')
  await page.click('[role="dialog"] button:has-text("إرسال رغم النقص")')
  await page.waitForSelector('text=القائمة للعرض فقط')
  assert(await cell(0, 0).isDisabled(), 'inputs locked after submission')
  log('submit to committee with incomplete warning → sheet locked')
  await logout()

  // ===== اللجنة: إعادة ثم اعتماد =====
  await login('اللجنة الامتحانية')
  await page.click('aside a:has-text("التدقيق والاعتماد")')
  await page.waitForSelector('text=التشريح الشعاعي للرأس والأطراف العليا')
  await shot('04-review-queue')
  await page.locator('tr', { hasText: 'التشريح الشعاعي للرأس والأطراف العليا' }).locator('a:has-text("تدقيق")').click()
  await page.waitForSelector('table.grade-grid')
  await page.click('button:has-text("إعادة للتعديل")')
  await page.fill('[role="dialog"] textarea', 'يرجى إكمال درجات بقية الطلبة')
  await page.click('[role="dialog"] button:has-text("إعادة القائمة")')
  await page.waitForSelector('text=معادة للتعديل')
  log('committee returned sheet with a note')
  await logout()

  await login('تدريسي')
  await page.waitForSelector('text=قائمة معادة للتعديل')
  await page.click('a:has-text("التشريح الشعاعي للرأس والأطراف العليا")')
  await page.waitForSelector('text=يرجى إكمال درجات بقية الطلبة')
  assert(!(await cell(0, 0).isDisabled()), 'returned sheet editable again')
  log('teacher sees return note and can edit again')
  await page.click('button:has-text("إرسال إلى اللجنة")')
  await page.click('[role="dialog"] button:has-text("إرسال")')
  await page.waitForSelector('text=القائمة للعرض فقط')
  await logout()

  await login('اللجنة الامتحانية')
  await page.click('aside a:has-text("التدقيق والاعتماد")')
  await page.locator('tr', { hasText: 'التشريح الشعاعي للرأس والأطراف العليا' }).locator('button:has-text("اعتماد")').click()
  await page.click('[role="dialog"] button:has-text("اعتماد")')
  await page.waitForSelector('text=تم اعتماد القائمة')
  log('committee approved from the review queue')
  await logout()

  // ===== معاون العميد: غلق الإدخال =====
  await login('معاون العميد')
  await page.click('aside a:has-text("التحكم بالإدخال")')
  await page.click('button:has-text("غلق الإدخال للجميع")')
  await page.click('[role="dialog"] button:has-text("غلق الإدخال")')
  await page.waitForSelector('text=إدخال الدرجات مغلق')
  await shot('05-entry-control')
  log('assistant dean closed grade entry with one click')
  await logout()

  await login('تدريسي')
  await page.waitForSelector('text=إدخال الدرجات مغلق حالياً')
  await page.click('a:has-text("فحوصات شعاعية للجهاز الصفراوي والتناسلي")')
  await page.waitForSelector('table.grade-grid')
  assert(await cell(0, 0).isDisabled(), 'teacher cannot edit while closed')
  await page.waitForSelector('text=مغلق حالياً من قبل الإدارة')
  log('teacher blocked while entry is closed')
  await logout()

  await login('معاون العميد')
  await page.click('aside a:has-text("التحكم بالإدخال")')
  await page.click('button:has-text("فتح الإدخال للجميع")')
  await page.click('[role="dialog"] button:has-text("فتح الإدخال")')
  await page.waitForSelector('text=إدخال الدرجات مفتوح')
  log('entry reopened')
  await logout()

  // ===== مقرر القسم: لصق الطلبة وإضافة مادة =====
  await login('مقرر القسم')
  await page.click('aside a:has-text("قسمي")')
  await page.waitForSelector('text=المرحلة الأولى')
  await shot('06-department')
  await page.locator('a[href*="/class/"][href$="/1/morning"]').click()
  await page.click('button:has-text("قائمة الطلبة")')
  await page.click('button:has-text("إضافة طلبة (نسخ ولصق)")')
  await page.fill('[role="dialog"] textarea', 'ت\tاسم الطالب\n1\tزيد كريم جواد علي\n2\tسارة نبيل حسن كاظم\n3\tزيد كريم جواد علي\n٤- مريم علي حسين جاسم')
  await page.waitForSelector('text=مكرر — سيتم تجاهله')
  await shot('07-paste-students')
  await page.click('[role="dialog"] button:has-text("إضافة 3 طالب")')
  await page.waitForSelector('text=تمت إضافة 3 طالب')
  const names = await page.locator('table.table-base tbody tr td:nth-child(2)').allInnerTexts()
  assert(JSON.stringify(names) === JSON.stringify(['زيد كريم جواد علي', 'سارة نبيل حسن كاظم', 'مريم علي حسين جاسم']), `paste order kept: ${names}`)
  log('head pasted student names (header skipped, duplicate skipped, order kept)')

  await page.click('button:has-text("المواد والدرجات")')
  await page.click('button:has-text("استيراد من الخطة الدراسية")')
  await page.waitForSelector('[role="dialog"]:has-text("مصطلحات طبية")')
  await shot('08-import-plan')
  await page.click('[role="dialog"] button:has-text("إضافة 9 مادة")')
  await page.waitForSelector('a:has-text("علم وظائف الاعضاء 1")')
  assert((await page.locator('a[href*="/subjects/"]').count()) === 9, 'imported 9 subjects from the study plan')
  log('head imported the stage-1 / term-1 subjects from the study plan (9 subjects with units)')

  await page.locator('button', { hasText: /^إضافة مادة$/ }).click()
  await page.fill('[role="dialog"] input[placeholder^="مثال"]', 'مبادئ الإسعافات الأولية')
  await page.click('[role="dialog"] [role="tab"]:has-text("نظري فقط")')
  await page.locator('[role="dialog"] label', { hasText: 'منتظر عادل الخفاجي' }).click()
  await page.click('[role="dialog"] button:has-text("حفظ المادة")')
  await page.waitForSelector('a:has-text("مبادئ الإسعافات الأولية")')
  log('head added a theory-only subject (30/70) and assigned a teacher')
  await logout()

  // ===== العميد: الدور الثاني =====
  await login('العميد')
  await page.click('aside a:has-text("التدقيق والاعتماد")')
  await page.click('button:has-text("الدور الثاني")')
  await page.click('button:has-text("مسودات")')
  await page.locator('table.table-base tbody tr').first().locator('a:has-text("تدقيق")').click()
  await page.waitForSelector('text=الامتحان النهائي — الدور الثاني')
  const r2row = page.locator('table.grade-grid tbody tr').first()
  const cw = Number((await r2row.locator('td').nth(2).innerText()).trim())
  const r2inputs = r2row.locator('input.cell-input')
  const nIn = await r2inputs.count()
  for (let i = 0; i < nIn; i++) {
    await r2inputs.nth(i).click()
    await page.keyboard.type('20')
  }
  await page.keyboard.press('Enter')
  const expected = String(Math.min(100, Math.round(cw + 20 * nIn)))
  assert((await r2row.locator('td').nth(4 + nIn + (nIn > 1 ? 1 : 0)).innerText()).trim() === expected, `round-2 total = coursework ${cw} + finals → ${expected}`)
  await page.waitForSelector('[data-save-state="saved"]', { timeout: 8000 })
  await shot('09-round2')
  log(`second round: coursework kept (${cw}) + new final exam → ${expected}`)

  // ===== العميد: الماستر شيت والنتائج =====
  await page.goto(`${BASE}#/class/d-cht/2/morning?tab=master&term=1`)
  await page.waitForSelector('text=الأوائل على المرحلة')
  await page.waitForSelector('th:has-text("مجموع الدرجات")')
  await page.waitForSelector('th:has-text("المعدل")')
  assert((await page.locator('td:has-text("د2")').count()) > 0, 'master sheet shows second-round rows')
  await shot('10-master-sheet')
  log('master sheet: coursework / final / total per subject + round-2 row + sum, weighted average, notes')

  await page.locator('table a[href*="/student/"]').first().click()
  await page.waitForSelector('.result-card:has-text("نتيجة الطالب")')
  await page.waitForSelector('.result-card:has-text("رئيس القسم")')
  await shot('11-student')
  log('student page: all subjects with grades + printable result card')

  await page.goto(`${BASE}#/class/d-cht/2/morning/results?term=1`)
  await page.waitForSelector('.result-card')
  assert((await page.locator('.result-card').count()) === 24, 'one result card per student (24)')
  await page.click('button:has-text("مكمل")')
  const carry = await page.locator('.result-card').count()
  assert(carry > 0 && carry < 24, `carry filter shows a subset (${carry})`)
  assert((await page.locator('.result-card').first().innerText()).includes('مكمل في'), 'carry result names the subject(s)')
  log(`batch result printing (24 cards, ${carry} مكمل with subject names)`)

  await page.goto(`${BASE}#/students`)
  await page.fill('input[placeholder^="اكتب جزءاً من اسم الطالب"]', 'زيد كريم')
  await page.waitForSelector('a[href*="/student/"]:has-text("زيد كريم جواد علي")')
  log('student search across departments')

  // ===== العميد: التقارير =====
  await page.goto(`${BASE}#/`)
  await page.waitForSelector('text=متابعة الإنجاز حسب القسم')
  await shot('12-dean-dashboard')
  log('dean dashboard')
  await page.goto(`${BASE}#/progress`)
  await page.waitForSelector('text=تقرير الإنجاز')
  await page.goto(`${BASE}#/audit`)
  await page.waitForSelector('text=اعتماد قائمة')
  await shot('13-audit')
  log('audit log shows workflow events')
  await logout()

  // ===== المدير: إنشاء حساب =====
  await login('مدير النظام')
  await page.click('aside a:has-text("المستخدمون")')
  await page.click('button:has-text("حساب جديد")')
  await page.fill('[role="dialog"] input[placeholder^="الاسم الثلاثي"]', 'تدريسي اختبار')
  await page.click('[role="dialog"] button:has-text("إنشاء الحساب")')
  await page.waitForSelector('text=بيانات الدخول')
  await shot('14-credentials')
  const uname = await page.locator('[role="dialog"] td.font-mono').first().innerText()
  const pwd = await page.locator('[role="dialog"] td.font-mono').nth(1).innerText()
  await page.click('[role="dialog"] button:has-text("تم")')
  log(`admin generated account ${uname}`)
  await logout()
  await page.fill('input[autocomplete="username"]', uname)
  await page.fill('input[autocomplete="current-password"]', pwd)
  await page.click('button[type="submit"]:has-text("دخول")')
  await page.waitForSelector('text=تعيين كلمة مرور جديدة')
  log('new user is forced to change the temporary password')
  const pw = page.locator('[role="dialog"] input[type="password"]')
  await pw.nth(0).fill(pwd)
  await pw.nth(1).fill('NewPass2026')
  await pw.nth(2).fill('NewPass2026')
  await page.click('[role="dialog"] button:has-text("حفظ كلمة المرور")')
  await page.waitForSelector('text=تم تغيير كلمة المرور بنجاح')
  log('password changed')

  // ===== الهاتف والوضع الليلي =====
  await logout()
  await page.setViewportSize({ width: 390, height: 844 })
  await login('مقرر القسم')
  await shot('15-mobile-dashboard')
  await page.evaluate(() => document.documentElement.classList.add('dark'))
  await page.goto(`${BASE}#/class/d-cht/2/morning?term=1`)
  await page.waitForSelector('text=مواد الفصل الأول')
  await shot('16-mobile-dark-class')
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 1)
  assert(!overflow, 'no horizontal page overflow on mobile')
  log('mobile layout without horizontal overflow + dark mode')

  assert(errors.length === 0, `console errors: ${errors.join(' | ')}`)
  log('no console errors')
  await browser.close()
  console.log(`\nALL E2E CHECKS PASSED (${step})`)
}

main().catch(async (e) => {
  console.error(e)
  process.exit(1)
})
