  await vpage.goto(`${BASE}#/verify/0000-0000-0000-0000`)
  await vpage.waitForSelector('text=رمز التحقق غير صحيح')
  await vctx.close()
  log('public QR verification page shows the official result without login; a wrong code is rejected')

  await page.goto(`${BASE}#/students`)
  await page.fill('input[placeholder^="اكتب جزءاً من اسم الطالب"]', 'زيد كريم')
  await page.waitForSelector('a[href*="/student/"]:has-text("زيد كريم جواد علي")')
  log('student search across departments')

  // ===== العميد: التقارير =====
  await page.goto(`${BASE}#/`)
  await page.waitForSelector('text=متابعة الإنجاز حسب القسم')
  await shot('12-dean-dashboard')
  log('dean dashboard')
  await page.goto(`${BASE}#/progress`)
  await page.waitForSelector('text=تقرير الإنجاز')
  await page.goto(`${BASE}#/audit`)
  await page.waitForSelector('text=اعتماد قائمة')
  await shot('13-audit')
  log('audit log shows workflow events')
  await logout()

  // ===== المدير: إنشاء حساب =====
  await login('مدير النظام')
  await page.click('aside a:has-text("المستخدمون")')
  await page.click('button:has-text("حساب جديد")')
  await page.locator('[role="dialog"] input[placeholder^="الاسم الثلاثي"]').pressSequentially('تدريسي اختبار', { delay: 15 })
  assert((await page.locator('[role="dialog"] input[placeholder^="الاسم الثلاثي"]').inputValue()) === 'تدريسي اختبار', 'name typed manually stays in the name field')
  await page.click('[role="dialog"] button:has-text("إنشاء الحساب")')
  await page.waitForSelector('text=بيانات الدخول')
  await shot('14-credentials')
  const uname = await page.locator('[role="dialog"] td.font-mono').first().innerText()
  const pwd = await page.locator('[role="dialog"] td.font-mono').nth(1).innerText()
  await page.click('[role="dialog"] button:has-text("تم")')
  log(`admin generated account ${uname}`)
  await logout()
  await page.fill('input[autocomplete="username"]', uname)
  await page.fill('input[autocomplete="current-password"]', pwd)
  await page.click('button[type="submit"]:has-text("دخول")')
  await page.waitForSelector('text=تعيين كلمة مرور جديدة')
  log('new user is forced to change the temporary password')
  const pw = page.locator('[role="dialog"] input[type="password"]')
  await pw.nth(0).fill(pwd)
  await pw.nth(1).fill('NewPass2026')
  await pw.nth(2).fill('NewPass2026')
  await page.click('[role="dialog"] button:has-text("حفظ كلمة المرور")')
  await page.waitForSelector('text=تم تغيير كلمة المرور بنجاح')
  log('password changed')

  // ===== إحصائيات اللجنة الامتحانية =====
  await logout()
  await login('العميد')
  await page.click('aside a:has-text("إحصائيات اللجنة الامتحانية")')
  await page.waitForSelector('text=النتائج حسب القسم')
  assert(!(await page.locator('aside a:has-text("ترحيل البيانات")').count()), 'migration tab removed')
  await page.click('label:has-text("النتائج المعتمدة فقط")')
  await page.waitForSelector('main td:has-text("تقنيات صحة المجتمع")')
  const collegeText = await page.locator('main').innerText()
  for (const t of ['نسبة النجاح', 'حسب المرحلة الدراسية', 'توزيع معدلات الطلبة', 'المواد الأقل نسبة نجاح', 'أوائل الكلية', 'الدور الثاني ودرجات القرار']) assert(collegeText.includes(t), `college statistics show ${t}`)
  await page.locator('main button:has-text("تقنيات صحة المجتمع")').first().click()
  await page.waitForSelector('text=الطلبة الراسبون والمكملون')
  assert((await page.locator('main h3:has-text("نسبة النجاح في كل مادة")').count()) >= 1, 'per-subject pass rates per stage')
  await page.click('main button[role=tab]:has-text("الفصل الثاني")')
  await page.waitForSelector('main h3:has-text("نسبة النجاح في كل مادة")')
  await page.emulateMedia({ media: 'print' })
  await page.waitForSelector('.print-only', { state: 'attached' })
  assert((await page.locator('.print-only').innerText()).includes('إحصائيات قسم تقنيات صحة المجتمع'), 'printable department statistics (PDF)')
  await page.emulateMedia({ media: 'screen' })
  const [xlsx] = await Promise.all([page.waitForEvent('download'), page.click('button:has-text("تصدير Excel")')])
  assert(!!(await xlsx.path()), 'statistics exported to Excel')
  await shot('17-statistics')
  log('committee statistics: college + department views, per-subject rates, failing students, print and Excel')

  // ===== بوابة الطلبة: الحسابات والبطاقات والنشر =====
  await page.click('aside a:has-text("بوابة الطلبة")')
  await page.waitForSelector('text=الصفوف الدراسية')
  await page.fill('input[placeholder*="student-results"]', 'https://example.org/student-results/')
  await page.click('main button:has-text("حفظ")')
  await page.waitForSelector('text=حُفظت إعدادات البوابة')
  await page.click('button:has-text("إنشاء الحسابات الناقصة")')
  await page.waitForSelector('text=حساب جديد')
  const portalRow = page.locator('main tbody tr', { hasText: 'تقنيات صحة المجتمع' }).first()
  await portalRow.locator('button:has-text("نشر")').first().click()
  assert((await page.locator('[role="dialog"]').innerText()).includes('مجموع سعيه في كل مادة فقط'), 'publish dialog explains what students will see')
  await page.click('[role="dialog"] button:has-text("نشر للطلبة")')
  await portalRow.locator('text=منشور').first().waitFor()
  await portalRow.locator('button:has-text("البطاقات")').click()
  await page.waitForSelector('[role="dialog"] td')
  assert(/\d{7}/.test(await page.locator('[role="dialog"] tbody tr').first().innerText()), 'access cards list a 7-digit login number')
  await page.emulateMedia({ media: 'print' })
  await page.waitForSelector('.print-only', { state: 'attached' })
  const cardText = await page.locator('.print-only').innerText()
  assert(cardText.includes('بوابة الطالب') && cardText.includes('الرمز السري') && cardText.includes('امسح للدخول مباشرة'), 'printable access cards with QR')
  await page.emulateMedia({ media: 'screen' })
  await page.click('[role="dialog"] button:has-text("إغلاق")')
  // فحص سجلات السنوات السابقة (في الوضع التجريبي لا نواقص)
  await page.click('button:has-text("فحص")')
  await page.waitForSelector('text=مربوطون بسجلات سنواتهم السابقة')
  assert((await page.locator('main').innerText()).includes('تنقصهم سجلات سنوات سابقة'), 'history check summary shown')
  // النتائج المحجوبة تُدار من بوابة الطلبة: رفع الحجب يعيدها فوراً
  const heldRow = page.locator('main tbody tr', { hasText: heldName }).filter({ hasText: 'يرجى مراجعة اللجنة الامتحانية.' })
