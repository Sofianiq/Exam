  assert((await page.locator('main').innerText()).includes('النتائج المحجوبة (1)'), 'withheld results listed in the portal page')
  await heldRow.locator('button:has-text("رفع الحجب")').click()
  await page.click('[role="dialog"] button:has-text("رفع الحجب")')
  await page.waitForSelector('text=لا توجد نتائج محجوبة')
  // درجات تغيّرت بعد النشر: يظهر زر «تحديث ما تغيّر» ويعيد النشر دفعة واحدة (الصف الذي بلا درجات لا يُعد متغيّراً)
